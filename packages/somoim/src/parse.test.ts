const at = (iso: string) => new Date(iso)
const POSTED = at('2026-09-20T12:00:00+09:00')

/** [텍스트, 기대 date, start, end] */
type Case = [string, string | null, (string | null)?, (string | null)?]

function check(cases: Case[], posted = POSTED) {
  for (const [text, date, start = null, end = null] of cases) {
    const r = parseSchedule(text, posted)
    if (date === null) {
      expect(r, text).toBeNull()
    } else {
      expect(r, text).toEqual({ date, startTime: start, endTime: end })
    }
  }
}

